/**
 * Test fixtures in `src/test/resources/fixtures`, generated by `src/test/python/make_fixtures.py` (nbtlib) from
 * `worlds/gtnh-initial-rwg` (GTNH 2.9.0-RC-2, read-only) plus synthetic chunks:
 * - `endlessids_-10_-4.zlib`: real chunk (-10,-4) from `region/r.-1.-1.mca` (EndlessIDs: BlocksB2Hi + Data2)
 * - `neid_synthetic.zlib`: NotEnoughIDs `Blocks16`/`Data16` section + vanilla/EndlessIDs section, `Biomes16`
 * - `vanilla_synthetic.zlib`: plain vanilla section, vanilla `Biomes`, not populated
 * - `level.dat`: real `FML.ItemData` entries for the ids used above, plus a synthetic `BlockAliases` entry
 * Expected values in the tests were decoded independently with nbtlib.
 */
object Fixtures {
    fun bytes(name: String): ByteArray = Fixtures::class.java.getResourceAsStream("/fixtures/$name")!!.use { it.readAllBytes() }

    val registry: FmlBlockRegistry by lazy {
        Compression.GZIP.decompress(bytes("level.dat").inputStream()).use { FmlBlockRegistry.read(it) }
    }

    fun loadChunk(
        name: String,
        biomes: LegacyBiomeMapper = LegacyBiomeMapper { Biome.DEFAULT },
    ): Chunk {
        val loader = LegacyChunkLoader(RegistryBlockStateMapper(registry), biomes, LegacyDimensions.OVERWORLD_TYPE)
        val data = bytes(name)
        return loader.load(data, 0, data.size, Compression.DEFLATE)
    }

    /** The identity state of a registry name (normalized key, contract C1). */
    fun state(
        name: String,
        meta: Int,
    ): BlockState = RegistryBlockStateMapper.identityState(name, meta)

    /** Writes a region file holding the given zlib chunk payload at chunk (x, z). */
    fun writeRegion(
        folder: Path,
        chunkX: Int,
        chunkZ: Int,
        payload: ByteArray,
    ) {
        val sectors = (payload.size + 5 + 4095) / 4096
        val buffer = ByteBuffer.allocate((2 + sectors) * 4096)
        buffer.putInt(((chunkZ and 31) shl 5 or (chunkX and 31)) * 4, (2 shl 8) or sectors)
        buffer.position(2 * 4096)
        buffer.putInt(payload.size + 1)
        buffer.put(2) // zlib
        buffer.put(payload)
        Files.createDirectories(folder)
        Files.write(folder.resolve("r.${chunkX shr 5}.${chunkZ shr 5}.mca"), buffer.array())
    }
}

class TestBiome(
    private val key: Key,
) : Biome by Biome.DEFAULT {
    override fun getKey(): Key = key
}
