package de.bluecolored.bluemap.gtnh.legacy

import de.bluecolored.bluemap.core.world.BlockState

/**
 * The 1.7.10 -> 1.13 block flattening table `flattening_1_7_10.tsv` (generated by
 * `src/test/python/gen_flattening_table.py` from PrismarineJS minecraft-data `legacy.json`, completed with the
 * 1.13.2 property defaults): `<id> <1.7.10 registry name> <meta> <1.13.2 state> <registered>` for the vanilla ids 1..175.
 *
 * Keyed by registry name, so it applies to Forge worlds whatever ids FML assigned. Metas that vanilla never uses
 * map to the block's lowest meta (that is how 1.7 renders them); `registered = 0` marks them, a real 1.13.2 upgrade
 * turns those into air.
 */
object VanillaFlattening {
    private const val RESOURCE = "flattening_1_7_10.tsv"

    private class Table(
        val byName: Map<String, Array<BlockState>>,
        val registered: Map<String, BooleanArray>,
        val ids: Map<Int, String>,
    )

    private val table: Table by lazy { load() }

    /** The 16 flattened states (index = meta) of a 1.7.10 vanilla registry name, or null if the name is not vanilla. */
    @JvmStatic
    fun states(registryName: String): Array<BlockState>? = table.byName[registryName]

    /** The flattened state of a vanilla registry name and meta (only the low 4 bits exist for vanilla blocks). */
    @JvmStatic
    fun state(
        registryName: String,
        meta: Int,
    ): BlockState? = table.byName[registryName]?.get(meta and 0xF)

    /** False if Mojang's 1.13 flattening table does not know this vanilla id:meta (a 1.13.2 upgrade drops it to air). */
    @JvmStatic
    fun isRegistered(
        registryName: String,
        meta: Int,
    ): Boolean = table.registered[registryName]?.get(meta and 0xF) ?: false

    /** The vanilla 1.7.10 block ids with their registry names (including `0 = minecraft:air`). */
    @JvmStatic
    fun vanillaBlockNames(): Map<Int, String> = table.ids

    private fun load(): Table {
        val stream =
            VanillaFlattening::class.java.getResourceAsStream(RESOURCE)
                ?: error("Missing resource $RESOURCE")
        val interned = HashMap<String, BlockState>()
        val byName = HashMap<String, Array<BlockState?>>()
        val registered = HashMap<String, BooleanArray>()
        val ids = HashMap<Int, String>()
        ids[0] = "minecraft:air"
        stream.bufferedReader().useLines { lines ->
            for (line in lines) {
                if (line.isBlank()) continue
                val (id, name, meta, state, known) = line.split('\t')
                ids[id.toInt()] = name
                byName.getOrPut(name) { arrayOfNulls(16) }[meta.toInt()] = interned.getOrPut(state) { BlockState.fromString(state) }
                registered.getOrPut(name) { BooleanArray(16) }[meta.toInt()] = known == "1"
            }
        }
        return Table(byName.mapValues { (_, states) -> states.requireNoNulls() }, registered, ids)
    }
}

/**
 * Decorates the identity mapping: vanilla (`minecraft:*`, ids <= 175 in 1.7.10) blocks become their flattened
 * 1.13 states, everything else stays as [delegate] maps it. Neighbour / block-entity dependent parts are
 * provided as [fixer]s ([VanillaFixers]).
 */
class FlatteningBlockStateMapper
    @JvmOverloads
    constructor(
        private val registry: FmlBlockRegistry,
        private val delegate: LegacyBlockStateMapper = RegistryBlockStateMapper(registry),
    ) : LegacyBlockStateMapper {
        private val fixers = VanillaFixers(registry)

        override fun map(
            id: Int,
            meta: Int,
        ): BlockState {
            if (id == 0) return BlockState.AIR
            val name = registry.name(id) ?: return delegate.map(id, meta)
            return VanillaFlattening.state(name, meta) ?: delegate.map(id, meta)
        }

        override fun fixer(state: BlockState): LegacyBlockFixer? = fixers.fixer(state) ?: delegate.fixer(state)
    }
